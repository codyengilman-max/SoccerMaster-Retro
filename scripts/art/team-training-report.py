"""Writes docs/art/team-training-v1/FRAME_REPORT.md from the derived-atlas manifest (run after build-team-training.py)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
m = json.loads((ROOT / 'src/assets/art/team-training-v1/manifest.json').read_text())
STAND = m['standVisibleHeight']
NEAR_DUP = 0.2   # mean normalised pixel difference to the next frame in the row; below this the poses read the same
SIZE_DRIFT = 0.08

out = ['# Team Training art v1: frame report', '',
       f"Status: **{m['status']}** (review build, not approved for shipping). Generated by `scripts/art/team-training-report.py` from `src/assets/art/team-training-v1/manifest.json`.", '',
       'Source sheets are unchanged copies in `source/`; every number below is measured on the derived runtime atlas.',
       f'Standing visible body height after per-sheet normalisation: {STAND} atlas px (protagonist outline excluded).', '',
       '## Flags per sheet', '',
       '| Sheet | Frame (row col) | Flag |', '|---|---|---|']
counts = {'clipped': 0, 'edge': 0, 'raised': 0, 'dup': 0, 'size': 0}
for name, e in m['sheets'].items():
    for f in e['frames']:
        where = f"{f['index']} ({f.get('row', f.get('pose'))} {f.get('column', '')})".replace(' )', ')')
        flags = []
        if f.get('clipped'):
            flags.append('clipped at the cell edge'); counts['clipped'] += 1
        if f.get('sourceEdge'):
            flags.append('touches the source sheet edge (may be cut off in the supplied art)'); counts['edge'] += 1
        if f.get('raisedFoot') and f.get('row') in ('receive', 'shuffle') and f.get('column') == 1:
            flags.append('first pose of the row has no planted foot'); counts['raised'] += 1
        d = f.get('diffToNext')
        if d is not None and d < NEAR_DUP:
            flags.append(f'near-duplicate of the next pose (diff {d})'); counts['dup'] += 1
        if f.get('row') in ('pass', 'receive') and abs(f['visibleHeight'] - STAND) / STAND > SIZE_DRIFT:
            flags.append(f"body height {f['visibleHeight']} vs {STAND} standing (>{int(SIZE_DRIFT*100)}%)"); counts['size'] += 1
        for fl in flags:
            out.append(f'| {name} | {where} | {fl} |')
out += ['', f"Totals: {counts['clipped']} clipped, {counts['edge']} source-edge, {counts['raised']} unplanted first poses, {counts['dup']} near-duplicates, {counts['size']} size drifts.", '',
        '## Missing keeper cycles', '',
        f"Each keeper strip has only the key poses {', '.join(m['keeperPoses'])}. Not supplied: {', '.join(m['missingKeeperCycles'])}.",
        'The game never invents them: a keeper save, catch or distribution shows as the nearest key pose (ready or stride) and Coach Code text, not an animated dive.', '',
        '## Facing', '', 'Every supplied outfield pose faces right or three-quarters right. Players moving up or down the screen use the side-on run, flipped toward their screen direction. No front or back views exist.', '']
(ROOT / 'docs/art/team-training-v1/FRAME_REPORT.md').write_text('\n'.join(out))
print(counts)
