"""Import the owner's SoccerMaster 9v9 Audited Library v1.2 (scenarios.json) verbatim into a framework-free TS module.

Run: python3 scripts/training/import-tactical-library.py
Cards are copied unchanged; the importer only adds gameRole (DM->6, CM->8, ST->9) and cardSha256, the SHA-256 of the
card's key-sorted compact JSON (same bytes as stableJson() in src/game/training12/library/sha256.ts).
tests/training12-tactical-library.test.ts re-reads the committed package and fails if anything here has drifted.
"""
import hashlib, json, os

DIR = 'docs/training/library-v1.2'
SRC = DIR + '/scenarios.json'
OUT = 'src/game/training12/library/tacticalLibrary.generated.ts'
ROLE = {'GK': 'GK', 'CB': 'CB', 'LB': 'LB', 'RB': 'RB', 'DM': '6', 'CM': '8', 'LW': 'LW', 'RW': 'RW', 'ST': '9'}
canon = lambda v: json.dumps(v, sort_keys=True, separators=(',', ':'), ensure_ascii=False)
sha = lambda b: hashlib.sha256(b).hexdigest()
raw = open(SRC, 'rb').read()
d = json.loads(raw)
assert d['version'] == '1.2' and len(d['scenarios']) == 48 and len(d['sources']) == 15
cards = [{**c, 'gameRole': ROLE[c['role']], 'cardSha256': sha(canon(c).encode())} for c in d['scenarios']]
files = {f: sha(open(os.path.join(DIR, f), 'rb').read()) for f in sorted(os.listdir(DIR)) if f in
         ('AUDIT.md', 'DEVON_READ_FIRST.md', 'LIBRARY.md', 'SOURCES.md', 'scenarios.json', 'validate_library.py')}
meta = {'file': 'scenarios.json', 'path': SRC, 'version': d['version'], 'kind': d['kind'], 'sha256': sha(raw), 'packageFiles': files,
        'uploadZip': 'SoccerMaster_9v9_Audited_v1.2.zip',
        'uploadZipSha256': '8dd4684a09e089efdd97e565b1ba6172caf0c94b13242f0adee9035f0df7202f',
        'status': 'DRAFT_BLOCKED_FOR_PLAYER_TRAINING',
        'supersedes': 'SoccerMaster_9v9_Tactical_Library_v1.md v1.0 (docs/training/library-v1/, kept as history)',
        'rulesSha256': sha(canon({'pitch_proposal': d['pitch_proposal'], 'rosters': d['rosters']}).encode())}
j = lambda v: json.dumps(v, indent=2, ensure_ascii=False)
ts = ('// GENERATED by scripts/training/import-tactical-library.py from ' + SRC + '. Do not edit by hand.\n'
      "import type { LibraryCard, LibraryMeta, LibraryPitch, LibraryRosterActor, LibrarySource } from './types';\n\n"
      f'export const LIBRARY: LibraryMeta = {j(meta)};\n\n'
      f"export const LIBRARY_ROSTERS: Readonly<Record<'H' | 'A', readonly LibraryRosterActor[]>> = {j(d['rosters'])};\n\n"
      f"export const LIBRARY_PITCH: LibraryPitch = {j(d['pitch_proposal'])};\n\n"
      f"export const LIBRARY_RETIRED_IDS: readonly string[] = {j(d['retired_ids'])};\n\n"
      f"export const LIBRARY_SOURCES: readonly LibrarySource[] = {j(d['sources'])};\n\n"
      f'export const LIBRARY_CARDS: readonly LibraryCard[] = {j(cards)};\n')
open(OUT, 'w').write(ts)
print(len(cards), meta['sha256'], meta['rulesSha256'])
