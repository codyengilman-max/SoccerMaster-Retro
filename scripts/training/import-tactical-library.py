"""Import SoccerMaster_9v9_Tactical_Library_v1.md verbatim into a framework-free TS module.

Run: python3 scripts/training/import-tactical-library.py
The test tests/training12-tactical-library.test.ts re-parses the committed markdown and fails if the
generated module, its hash, or any brief field has drifted.
"""
import hashlib, json, re

SRC = 'docs/training/library-v1/SoccerMaster_9v9_Tactical_Library_v1.md'
OUT = 'src/game/training12/library/tacticalLibraryV1.generated.ts'
ROLE = {'GK': 'GK', 'CB': 'CB', 'LB': 'LB', 'RB': 'RB', 'DM': '6', 'CM': '8', 'LW': 'LW', 'RW': 'RW', 'ST': '9'}
FIELD = {'Setup/cue': 'setup', 'Cue': 'setup', 'Decision': 'preferredCondition', 'Alternative': 'acceptableAlternative',
         'Error': 'misconception', 'Team response': 'teamResponse', 'Response': 'teamResponse', 'Coach': 'coachFeedback',
         'Counterfactual': 'counterfactualTest', 'Variation': 'counterfactualTest'}
raw = open(SRC, 'rb').read()
text = raw.decode('utf8')
briefs = []
for h in re.finditer(r'^### (\w+) — (.+?) \[(S[\dS,]+)\]\n(.+?)$', text, re.M):
    bid, title, srcs, body = h.groups()
    parts = re.split(r'(?:^|(?<=\. )|(?<=” ))(' + '|'.join(re.escape(k) for k in FIELD) + r'): ', body)
    rec = {'id': bid, 'title': title, 'role': ROLE[re.match(r'[A-Z]+', bid).group(0)], 'sourceIds': srcs.split(','), 'text': body}
    for k, v in zip(parts[1::2], parts[2::2]):
        rec[FIELD[k]] = v.strip()
    m = re.search(r'Mirror (\w+)', body)
    rec['mirrorOf'] = m.group(1) if m else None
    missing = [f for f in set(FIELD.values()) if f not in rec]
    assert not missing, (bid, missing)
    rec['briefSha256'] = hashlib.sha256(body.encode('utf8')).hexdigest()
    briefs.append(rec)
assert len(briefs) == 27, len(briefs)
srcs = []
for m in re.finditer(r'^- (S\d) — (.+?)\. (Supports|Governs) (.+?) (https://\S+)$', text, re.M):
    srcs.append({'id': m.group(1), 'citation': m.group(2), 'supports': (m.group(3) + ' ' + m.group(4)), 'url': m.group(5)})
assert len(srcs) == 7, len(srcs)
meta = {'file': SRC.split('/')[-1], 'path': SRC, 'version': '1.0', 'sha256': hashlib.sha256(raw).hexdigest(),
        'uploadZip': 'SoccerMaster_9v9_Tactical_Library_v1.zip',
        'uploadZipSha256': '1505c7dfbd2837c92b0a8f32db3b8aad93f2e2845f7e212cd282deb13b4f18ac',
        'status': 'SOURCE_INFORMED_DRAFT', 'adaptationType': 'authored_9v9_brief'}
ts = ('// GENERATED by scripts/training/import-tactical-library.py from ' + SRC + '. Do not edit by hand.\n'
      'import type { LibraryBrief, LibraryMeta, LibrarySourceRef } from \'./types\';\n\n'
      'export const LIBRARY_V1: LibraryMeta = ' + json.dumps(meta, indent=2, ensure_ascii=False) + ';\n\n'
      'export const LIBRARY_V1_SOURCES: readonly LibrarySourceRef[] = ' + json.dumps(srcs, indent=2, ensure_ascii=False) + ';\n\n'
      'export const LIBRARY_V1_BRIEFS: readonly LibraryBrief[] = ' + json.dumps(briefs, indent=2, ensure_ascii=False) + ';\n')
open(OUT, 'w').write(ts)
print(len(briefs), meta['sha256'])
